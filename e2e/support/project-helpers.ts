function getFileTree(page: Page) {
  return page.getByRole("complementary").first();
}

function withRequiredRootFolders(fileTree: ProjectFileNode[]): ProjectFileNode[] {
  const rootIds = new Set(fileTree.map((node) => node.id));

  return [
    rootIds.has("table-setups")
      ? null
      : {
          id: "table-setups",
          name: "Table setups",
          type: "folder" as const,
          children: []
        },
    ...fileTree,
    rootIds.has("assets")
      ? null
      : {
          id: "assets",
          name: "Assets",
          type: "folder" as const,
          children: []
        }
  ].filter((node): node is ProjectFileNode => Boolean(node));
}

function findNodeParentId(
  fileTree: ProjectFileNode[],
  nodeId: string,
  parentId: string | null = null
): string | null | undefined {
  for (const node of fileTree) {
    if (node.id === nodeId) {
      return parentId;
    }

    if (node.type === "folder") {
      const childParentId = findNodeParentId(node.children ?? [], nodeId, node.id);

      if (childParentId !== undefined) {
        return childParentId;
      }
    }
  }

  return undefined;
}

function escapeRegExp(value: string) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

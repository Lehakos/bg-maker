import type {
  CreateProjectResponse,
  GetProjectResponse,
  Project,
  ProjectFileNode,
  ProjectObjectKind,
  ProjectObjectNode
} from "@bg-maker/shared";
import { expect, type Locator, type Page } from "@playwright/test";
